ALTER TABLE examinations ENABLE ROW LEVEL SECURITY;
ALTER TABLE answer_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE scanned_answers ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all operations for instructors" ON instructors FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations for students" ON students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations for examinations" ON examinations FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations for answer_keys" ON answer_keys FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations for scanned_answers" ON scanned_answers FOR ALL USING (true) WITH CHECK (true);

