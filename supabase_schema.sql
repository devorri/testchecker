-- 1. Create Instructors Table
CREATE TABLE IF NOT EXISTS instructors (
  instructor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  password VARCHAR(255) DEFAULT 'password123',
  department VARCHAR(100) DEFAULT 'CCIT Department',
  role VARCHAR(50) DEFAULT 'instructor',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Students Table
CREATE TABLE IF NOT EXISTS students (
  student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_number VARCHAR(50) UNIQUE NOT NULL,
  name VARCHAR(100) NOT NULL,
  section VARCHAR(50) NOT NULL,
  course VARCHAR(100) NOT NULL,
  year_level VARCHAR(50) DEFAULT '3rd Year',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Examinations Table
CREATE TABLE IF NOT EXISTS examinations (
  exam_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  subject VARCHAR(150) NOT NULL,
  exam_date VARCHAR(50) NOT NULL,
  instructor_id BIGINT DEFAULT 101,
  total_questions INT NOT NULL DEFAULT 20,
  options_per_question INT NOT NULL DEFAULT 5,
  section VARCHAR(50) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Answer Keys Table
CREATE TABLE IF NOT EXISTS answer_keys (
  answerkey_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_id BIGINT UNIQUE NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
  correct_answers JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Create Scanned Answers / Results Table
CREATE TABLE IF NOT EXISTS scanned_answers (
  scan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT,
  student_number VARCHAR(50),
  student_name VARCHAR(100),
  exam_id BIGINT,
  student_answers JSONB NOT NULL,
  score INT NOT NULL DEFAULT 0,
  total INT NOT NULL DEFAULT 20,
  percentage NUMERIC(5,2) NOT NULL DEFAULT 0.00,
  remarks VARCHAR(50) NOT NULL DEFAULT 'FAILED',
  date_generated VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- ENABLE ROW LEVEL SECURITY (RLS) & ALLOW PUBLIC ACCESS FOR THE APP
-- ==============================================================================
ALTER TABLE instructors ENABLE ROW LEVEL SECURITY;
